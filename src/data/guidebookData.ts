// 숙소 변경 시 일정표 내용을 새로운 숙소 정보로 동적으로 치환하는 함수
export function applyAccommodationToSchedule(
  hotel: Accommodation,
  currentSchedule: ScheduleItem[]
): ScheduleItem[] {
  const isUmeda = hotel.area.includes('우메다');

  return currentSchedule.map((item) => {
    // 1일차 16:10 체크인 & 짐 풀기
    if (item.id === 'd1-3') {
      return {
        ...item,
        title: `숙소 체크인 & 짐 풀기 (${hotel.nameKo})`,
        location: `${hotel.nameKo} (${hotel.nearestStation})`,
        description: `${hotel.checkInGuide} ${hotel.roomType}. 프론트에 3일차 짐보관 사전 문의.`,
        badge: `4인 가족 베이스캠프 (${hotel.area})`,
        emergencyTip: `일행 분산 시 집결지로 온 가족이 [${hotel.nameKo}] 로비를 기억하세요!`,
      };
    }
    // 1일차 21:30 숙소 복귀 및 휴식
    if (item.id === 'd1-7') {
      return {
        ...item,
        title: `숙소 복귀 및 휴식 (${hotel.nameKo})`,
        location: hotel.nameKo,
        description: `도톤보리에서 ${hotel.transitToDotonbori}. 다음날 USJ 오픈런을 위해 가족 모두 족욕 후 일찍 취침 권장!`,
      };
    }
    // 2일차 08:10 USJ로 이동
    if (item.id === 'd2-2') {
      return {
        ...item,
        title: '유니버설시티역(USJ)으로 이동',
        location: `${hotel.nameKo} → ${hotel.transitToUSJ}`,
        description: `${hotel.nameKo}에서 출발. ${hotel.transitToUSJ}. ICOCA 카드 태그로 빠르게 통과.`,
        travelTime: isUmeda ? '이동 약 16~20분 (우메다 단축 코스)' : '이동 약 25~30분 소요',
      };
    }
    // 2일차 19:00 숙소 복귀 & 다이닝 저녁
    if (item.id === 'd2-6') {
      return {
        ...item,
        title: `숙소 복귀 & 저녁 식사 (${hotel.nameKo})`,
        location: `${hotel.nameKo} 객실 / 인근 식당`,
        description: `하루 종일 2만 보 걸은 가족들을 위해 551 호라이 만두와 테이크아웃 요리를 곁들여 ${hotel.nameKo}에서 편안히 식사.`,
      };
    }
    // 3일차 09:00 체크아웃 & 짐 보관
    if (item.id === 'd3-1') {
      return {
        ...item,
        title: `체크아웃 & 짐 보관 (${hotel.nameKo})`,
        location: `${hotel.nameKo} 프론트 데스크`,
        description: `${hotel.nameKo} 프론트에 캐리어 4개 보관 의뢰. (오사카성 관광 후 찾으러 복귀 예정).`,
      };
    }
    // 3일차 15:00 숙소 복귀 & 짐 찾기 및 면세 쇼핑
    if (item.id === 'd3-4') {
      return {
        ...item,
        title: `숙소 복귀 & 짐 찾기 (${hotel.nameKo})`,
        location: `${hotel.nameKo} 로비`,
        description: `${hotel.nameKo}에서 보관해둔 4인 캐리어를 찾고 인근에서 면세 쇼핑 품목과 액체류를 캐리어 안에 최종 패킹한 뒤 공항 이동 준비.`,
      };
    }
    return item;
  });
}

